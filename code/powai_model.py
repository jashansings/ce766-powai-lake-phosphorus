"""
CE766 Watershed Management - Final project, Jashanpreet Singh (23B0985)
Powai Lake annual water + phosphorus budget model with an internal-recycling term
(Carpenter et al., 1999 form), integrated exactly over each year.

All values marked ASSUMED are not measured for Powai; values marked REPORTED come
from a published source; SYNTHETIC means generated by a random-number generator.
"""
import numpy as np

# ---------------- Lake geometry (REPORTED / ASSUMED) ----------------
A_LAKE = 2.1e6        # m2, water-spread area (proposal; Lekshmi et al. 2021 give 2.2 km2)
DEPTH = 2.5           # m, effective mean depth after siltation (ASSUMED, from proposal)
V = A_LAKE * DEPTH    # m3 = 5.25e6
A_CATCH = 6.61e6      # m2, catchment area (REPORTED, Lekshmi et al. 2021)

# ---------------- Water budget (ASSUMED coefficients) ----------------
RAIN_MEAN = 2250.0    # mm/yr, ASSUMED long-term mean (synthetic rainfall generator)
RAIN_SD = 400.0       # mm/yr, ASSUMED inter-annual s.d.
RUNOFF_COEF = 0.60    # ASSUMED annual runoff coefficient, urbanised hilly catchment
EVAP = 1.6            # m/yr open-water evaporation, ASSUMED
SEWAGE_MLD = 18.0     # ML/day untreated sewage (figure cited in my proposal; BMC)
Q_SEW = SEWAGE_MLD * 1e3 * 365  # m3/yr = 6.57e6

# ---------------- Phosphorus budget ----------------
C_SEW = 5.0           # mg/L TP in raw sewage, ASSUMED (typical Indian domestic sewage 4-8 mg/L)
C_RUN = 0.22          # mg/L TP in catchment runoff, ASSUMED (kept from preliminary work)
TP_OBS = 0.93         # mg/L, mean TP at lake centre 2018-20 (REPORTED, Lekshmi et al. 2021)
X_OBS = TP_OBS * V / 1e6  # t of P in the lake corresponding to TP_OBS
R_REL_MG = 5.0        # mg P/m2/day max sediment release under anoxia, ASSUMED nominal
M_HALF = 2.0          # t, half-saturation stock of recycling term, ASSUMED
Q_HILL = 8.0          # Hill exponent, kept from preliminary work
X_CRIT = 1.0          # t, threshold kept from preliminary report (= 0.19 mg/L)


def water_budget(rain_mm):
    """Annual water budget (m3/yr). Storage change assumed zero (weir-controlled lake)."""
    P = rain_mm / 1000.0
    q_run = RUNOFF_COEF * P * A_CATCH
    q_rain = P * A_LAKE
    q_evap = EVAP * A_LAKE
    q_out = q_run + q_rain + Q_SEW - q_evap
    return dict(runoff=q_run, direct_rain=q_rain, sewage=Q_SEW, evaporation=q_evap, outflow=q_out)


def r_max(rel_mg=R_REL_MG):
    """Maximum internal load (t/yr) = release rate x lake area."""
    return rel_mg * A_LAKE * 365 / 1e9


A0 = Q_SEW * C_SEW / 1e6  # t/yr, untreated sewage P load (32.9 t/yr)


def calibrate_sigma(rel_mg=R_REL_MG, c_sew=C_SEW):
    """Net settling rate sigma (1/yr) so that the steady state with today's loads
    (no control, mean rainfall, recycling fully on) equals the observed lake TP."""
    wb = water_budget(RAIN_MEAN)
    rho = wb['outflow'] / V
    load = Q_SEW * c_sew / 1e6 + wb['runoff'] * C_RUN / 1e6 + r_max(rel_mg) * hill(X_OBS)
    k = load / X_OBS
    return k - rho, rho


def hill(X, m=M_HALF, q=Q_HILL):
    Xq = np.power(np.maximum(X, 0), q)
    return Xq / (m ** q + Xq)


SIGMA, RHO_MEAN = calibrate_sigma()


def simulate(u, rain, X0=X_OBS, sigma=SIGMA, rel_mg=R_REL_MG, c_sew=C_SEW,
             m=M_HALF, q=Q_HILL):
    """u: (T,) or (N,T) fraction of sewage P load removed each year.
    rain: (R,T) rainfall replicates (mm). Returns X with shape (..., R, T) at end of each year.
    Exact solution of dX/dt = L - kX over a year, with recycling evaluated at start of year."""
    u = np.atleast_2d(u)                     # (N,T)
    N, T = u.shape
    a = (1 - u) * Q_SEW * c_sew / 1e6        # (N,T) anthropogenic load t/yr
    P = rain / 1000.0
    q_run = RUNOFF_COEF * P * A_CATCH
    q_out = q_run + P * A_LAKE + Q_SEW - EVAP * A_LAKE
    rho = q_out / V                          # (R,T)
    Y = q_run * C_RUN / 1e6                  # (R,T) natural P load
    k = rho + sigma
    ek = np.exp(-k)
    rm = r_max(rel_mg)
    X = np.full((N, rain.shape[0]), X0)
    out = np.empty((N, rain.shape[0], T))
    for t in range(T):
        L = a[:, t:t + 1] + Y[None, :, t] + rm * hill(X, m, q)
        X = X * ek[None, :, t] + L / k[None, :, t] * (1 - ek[None, :, t])
        out[:, :, t] = X
    return out


def rain_replicates(R=100, T=25, seed=2026):
    """SYNTHETIC rainfall: normal(2250, 400) mm, clipped to 1300-3800 mm."""
    rng = np.random.default_rng(seed)
    return np.clip(rng.normal(RAIN_MEAN, RAIN_SD, (R, T)), 1300, 3800)


# ---------------- Objectives ----------------
DELTA = 0.05          # discount rate, ASSUMED (range 0.03-0.07)
COST_LIN = 5.3        # Rs crore/yr for full secondary treatment/diversion of 18 MLD, ASSUMED
COST_QUAD = 2.0       # Rs crore/yr extra for tertiary P removal at u=1, ASSUMED
INERTIA_TOL = 0.10    # max |change in u| counted as "no policy change"


def objectives(u, X):
    u = np.atleast_2d(u)
    T = u.shape[1]
    disc = (1 + DELTA) ** -np.arange(T)
    cost = ((COST_LIN * u + COST_QUAD * u ** 2) * disc).sum(axis=1)       # Rs crore (PV)
    mean_tp = X.mean(axis=(1, 2)) * 1e6 / V                                 # mg/L
    rel = (X < X_CRIT).mean(axis=(1, 2))                                    # fraction
    inertia = (np.abs(np.diff(u, axis=1)) <= INERTIA_TOL).mean(axis=1)    # fraction
    return cost, mean_tp, rel, inertia


