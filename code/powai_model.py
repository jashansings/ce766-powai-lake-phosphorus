# ---------------- Direct policy search (closed-loop rule) ----------------
N_RBF = 2


def dps_rule(theta, X):
    """theta: (N, 3*N_RBF) = centres c (in units of X_OBS), radii r, weights w.
    X: (N, R) lake P stock at start of year. Returns u in [0, 1] with shape (N, R).
    u = clip(sum_i w_i * exp(-((X/X_OBS - c_i)/r_i)^2), 0, 1)   (Quinn et al., 2017)."""
    th = np.atleast_2d(theta)
    c = th[:, 0:N_RBF][:, :, None]
    r = th[:, N_RBF:2 * N_RBF][:, :, None]
    w = th[:, 2 * N_RBF:3 * N_RBF][:, :, None]
    z = (X / X_OBS)[:, None, :]
    u = (w * np.exp(-((z - c) / np.maximum(r, 1e-3)) ** 2)).sum(axis=1)
    return np.clip(u, 0.0, 1.0)


def two_level_rule(theta, X):
    """theta: (N,3) = (u_low, u_high, X_switch in t). u = u_high if X > X_switch else u_low."""
    th = np.atleast_2d(theta)
    return np.where(X > th[:, 2:3], th[:, 1:2], th[:, 0:1])


RULE = two_level_rule   # rule used by simulate_dps (dps_rule = 2-RBF version, tried first)


def simulate_dps(theta, rain, X0=X_OBS, sigma=SIGMA, rel_mg=R_REL_MG, c_sew=C_SEW,
                 m=M_HALF, q=Q_HILL):
    """Returns X (N,R,T) at end of each year and u (N,R,T) applied each year."""
    th = np.atleast_2d(theta)
    N = th.shape[0]; R, T = rain.shape
    P = rain / 1000.0
    q_run = RUNOFF_COEF * P * A_CATCH
    rho = (q_run + P * A_LAKE + Q_SEW - EVAP * A_LAKE) / V
    Y = q_run * C_RUN / 1e6
    k = rho + sigma; ek = np.exp(-k)
    rm = r_max(rel_mg); a0 = Q_SEW * c_sew / 1e6
    X = np.full((N, R), X0, dtype=float)
    Xo = np.empty((N, R, T)); Uo = np.empty((N, R, T))
    for t in range(T):
        u = RULE(th, X)
        L = (1 - u) * a0 + Y[None, :, t] + rm * hill(X, m, q)
        X = X * ek[None, :, t] + L / k[None, :, t] * (1 - ek[None, :, t])
        Xo[:, :, t] = X; Uo[:, :, t] = u
    return Xo, Uo


def objectives_dps(X, U):
    T = U.shape[2]
    disc = (1 + DELTA) ** -np.arange(T)
    cost = ((COST_LIN * U + COST_QUAD * U ** 2) * disc).sum(axis=2).mean(axis=1)
    mean_tp = X.mean(axis=(1, 2)) * 1e6 / V
    rel = (X < X_CRIT).mean(axis=(1, 2))
    inertia = (np.abs(np.diff(U, axis=2)) <= INERTIA_TOL).mean(axis=(1, 2))
    return cost, mean_tp, rel, inertia
